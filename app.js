      '<div class="compact-item"><div><strong>' + esc(v.brand) + '</strong><small>' + esc(v.code) + '</small></div><span class="expiry-date">' + (daysUntil(v.expiryDate) === 0 ? "Today" : daysUntil(v.expiryDate) + " days") + '</span></div>'
